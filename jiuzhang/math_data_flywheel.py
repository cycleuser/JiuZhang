# ── Data Structures ──────────────────────────────────────────────────

class DifficultyLevel(Enum):
    ELEMENTARY = "elementary"
    INTERMEDIATE = "intermediate"
    ADVANCED = "advanced"
    RESEARCH = "research"


@dataclass
class MathProblem:
    """A math problem with ground truth."""
    id: str
    category: str
    difficulty: DifficultyLevel
    instruction_zh: str
    instruction_en: str
    input_zh: str
    input_en: str
    answer_zh: str
    answer_en: str
    sympy_expression: Optional[str] = None  # For verification
    solution_steps: Optional[List[str]] = None


@dataclass
class ModelResponse:
    """Model's response to a problem."""
    problem_id: str
    response_zh: str
    response_en: str
    is_correct: bool
    error_type: Optional[str] = None  # "calculation", "concept", "reasoning", "format"
    confidence: float = 0.0


@dataclass
class FlywheelSample:
    """A training sample generated by the flywheel."""
    problem: MathProblem
    source: str  # "error_expansion", "persona_injection", "behavior_tree", "adversarial"
    parent_problem_id: Optional[str] = None
    difficulty_increase: float = 0.0  # How much harder than parent
    verification_methods: List[str] = field(default_factory=list)
    verification_consensus: bool = True


# ── Error Collector ──────────────────────────────────────────────────

class ErrorCollector:
    """Collect and categorize model errors."""

    def __init__(self):
        self.errors: List[Tuple[MathProblem, ModelResponse]] = []
        self.error_stats: Dict[str, int] = {}
        self.category_errors: Dict[str, List[Tuple[MathProblem, ModelResponse]]] = {}

    def record_error(self, problem: MathProblem, response: ModelResponse):
        """Record a model error."""
        if not response.is_correct:
            self.errors.append((problem, response))
            error_type = response.error_type or "unknown"
            self.error_stats[error_type] = self.error_stats.get(error_type, 0) + 1
            
            cat = problem.category
            if cat not in self.category_errors:
                self.category_errors[cat] = []
            self.category_errors[cat].append((problem, response))

    def get_errors_by_category(self, category: str) -> List[Tuple[MathProblem, ModelResponse]]:
        return self.category_errors.get(category, [])

    def get_most_frequent_error_type(self) -> Optional[str]:
        if not self.error_stats:
            return None
        return max(self.error_stats, key=self.error_stats.get)

    def get_stats(self) -> Dict:
        return {
            "total_errors": len(self.errors),
            "by_type": dict(self.error_stats),
            "by_category": {k: len(v) for k, v in self.category_errors.items()},
        }


