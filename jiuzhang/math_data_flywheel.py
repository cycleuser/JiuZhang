    def generate_from_errors(self, errors: List[Tuple[MathProblem, ModelResponse]], 
                             count_per_error: int = 2) -> List[MathProblem]:
        """Generate harder examples from collected errors."""
        all_harder = []
        
        for problem, response in errors:
            # Check input text for problem type indicators
            input_text = f"{problem.input_zh} {problem.input_en} {problem.instruction_zh} {problem.instruction_en}".lower()
            
            if problem.category == "calculus":
                if "deriv" in input_text or "导数" in input_text:
                    all_harder.extend(self.expand_derivative_problem(problem, count_per_error))
                elif "integ" in input_text or "积分" in input_text:
                    all_harder.extend(self.expand_integral_problem(problem, count_per_error))
                else:
                    # Default to derivative expansion for calculus problems
                    all_harder.extend(self.expand_derivative_problem(problem, count_per_error))
            elif problem.category == "algebra":
                all_harder.extend(self.expand_equation_problem(problem, count_per_error))
            else:
                # For other categories, try equation expansion as default
                all_harder.extend(self.expand_equation_problem(problem, count_per_error))
        
        return all_harder


