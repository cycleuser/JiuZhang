                input_en=f"{a1}x + {b1}y = {c1}\n{a2}x + {b2}y = {c2}",
                answer_zh=f"x = {solutions[self.x]}, y = {solutions[self.y]}",
                answer_en=f"x = {solutions[self.x]}, y = {solutions[self.y]}",
