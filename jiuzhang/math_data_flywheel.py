# ── Behavior Tree Expander ───────────────────────────────────────────

class BehaviorTreeExpander:
    """Convert linear math problems into branching decision trees.
    
    For example, solving a quadratic equation:
    - If discriminant > 0: two real roots
    - If discriminant = 0: one repeated root
    - If discriminant < 0: two complex roots
    
    Each branch becomes a separate training scenario.
    """

    def __init__(self, seed: int = 42):
        self.rng = random.Random(seed)
        self.x = symbols('x')

    def expand_quadratic_solver(self, base_problem: MathProblem) -> List[MathProblem]:
        """Expand quadratic solving into behavior tree branches."""
        branches = []
        
        # Generate problems for each discriminant case
        cases = [
            ("positive_discriminant", "判别式>0，两个不同实根", "Δ>0, two distinct real roots", 1, 10),
            ("zero_discriminant", "判别式=0，一个重根", "Δ=0, one repeated root", 0, 0),
            ("negative_discriminant", "判别式<0，两个复根", "Δ<0, two complex roots", -10, -1),
        ]
        
        for branch_name, desc_zh, desc_en, disc_min, disc_max in cases:
            # Generate coefficients that produce the desired discriminant sign
            for _ in range(2):
                a = self.rng.randint(1, 3)
                b = self.rng.randint(-5, 5)
                # Choose c to get desired discriminant sign
                # Δ = b² - 4ac
                target_disc = self.rng.randint(disc_min, disc_max)
                # b² - 4ac = target_disc => c = (b² - target_disc) / (4a)
                c_num = b**2 - target_disc
                if c_num % (4*a) == 0:
                    c = c_num // (4*a)
                else:
                    c = self.rng.randint(-5, 5)
                    target_disc = b**2 - 4*a*c
                
                actual_disc = b**2 - 4*a*c
                eq = Eq(a*self.x**2 + b*self.x + c, 0)
                solutions = solve(eq, self.x)
                
                branches.append(MathProblem(
                    id=f"bt_quad_{branch_name}_{hashlib.md5(f'{a}{b}{c}'.encode()).hexdigest()[:6]}",
                    category="algebra",
                    difficulty=DifficultyLevel.INTERMEDIATE,
                    instruction_zh=f"解一元二次方程（{desc_zh}）",
                    instruction_en=f"Solve quadratic equation ({desc_en})",
                    input_zh=f"{a}x² + {b}x + {c} = 0\n提示：判别式 Δ = {actual_disc}",
                    input_en=f"{a}x² + {b}x + {c} = 0\nHint: discriminant Δ = {actual_disc}",
                    answer_zh=f"Δ = {actual_disc}\nx = {solutions}",
                    answer_en=f"Δ = {actual_disc}\nx = {solutions}",
                    sympy_expression=f"solve({a}*x**2 + {b}*x + {c} = 0)",
                    solution_steps=[
                        f"Compute discriminant: Δ = b²-4ac = {b}²-4·{a}·{c} = {actual_disc}",
                        f"Since Δ {'>' if actual_disc > 0 else '=' if actual_disc == 0 else '<'} 0: {desc_zh}",
                        f"Apply quadratic formula: x = (-b ± √Δ) / 2a",
                        f"x = {solutions}",
                    ],
                ))
        
        return branches

    def expand_limit_problem(self, base_problem: MathProblem) -> List[MathProblem]:
        """Expand limit problems with different approach branches."""
        branches = []
        
        limit_cases = [
            ("direct_substitution", "直接代入法", "direct substitution", 
             lambda: (self.x**2 + 3*self.x + 2, self.x, 1, 6)),
            ("lhopital", "洛必达法则", "L'Hôpital's rule",
             lambda: (sp.sin(self.x)/self.x, self.x, 0, 1)),
            ("factorization", "因式分解法", "factorization",
             lambda: ((self.x**2 - 4)/(self.x - 2), self.x, 2, 4)),
        ]
        
        for method_name, method_zh, method_en, gen_func in limit_cases:
            func, var, target, correct_val = gen_func()
            lim = limit(func, var, target)
            
            branches.append(MathProblem(
                id=f"bt_limit_{method_name}_{hashlib.md5(str(func).encode()).hexdigest()[:6]}",
                category="calculus",
                difficulty=DifficultyLevel.INTERMEDIATE,
                instruction_zh=f"求极限（{method_zh}）",
                instruction_en=f"Find the limit ({method_en})",
                input_zh=f"lim(x→{target}) {func}",
                input_en=f"lim(x→{target}) {func}",
                answer_zh=f"lim(x→{target}) {func} = {lim}\n方法：{method_zh}",
                answer_en=f"lim(x→{target}) {func} = {lim}\nMethod: {method_en}",
                sympy_expression=f"limit({func}, {var}, {target}) = {lim}",
                solution_steps=[
                    f"Identify the form: as x→{target}, {func} approaches...",
                    f"Apply {method_en}",
                    f"lim(x→{target}) {func} = {lim}",
                ],
            ))
        
        return branches

    def expand_problem(self, problem: MathProblem) -> List[MathProblem]:
        """Expand a problem into behavior tree branches."""
        if "二次" in problem.input_zh or "quadratic" in problem.input_en.lower():
            return self.expand_quadratic_solver(problem)
        elif "极限" in problem.input_zh or "limit" in problem.input_en.lower():
            return self.expand_limit_problem(problem)
        else:
            # Generic expansion: create variants with different parameter ranges
            return []


