"""Math Data Flywheel for JiuZhang.

Implements the AgenticQwen-style dual data flywheel adapted for mathematics education:

1. **Error-Driven Hard Example Generation**: Collect model failures, generate harder variants
   via Self-Instruct expansion (adjust values, add constraints, combine concepts).

2. **Persona Injection**: Rewrite abstract math problems into real-world contexts
   (physics, chemistry, economics) to increase surface-form diversity.

3. **Behavior Tree Expansion**: Convert linear problem-solving paths into branching
   decision trees based on intermediate results (e.g., "if discriminant > 0, use formula A;
   if discriminant = 0, use formula B; if discriminant < 0, complex roots").

4. **Adversarial Problem Generation**: Create problems with common misconceptions,
   misleading hints, or trap answers to train robustness.

5. **Multi-Verification Consistency Filter**: Only keep samples where multiple
   verification methods agree on the answer.

The flywheel runs iteratively:
  Model trains → Model evaluated → Failures collected → Hard examples generated →
  New data added → Model retrains → ...

This creates a self-improving loop where each round produces more challenging,
more diverse training data.
"""

