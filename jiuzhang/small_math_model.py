@dataclass
class SmallMathModelConfig:
    base_model: str = "Qwen/Qwen3.5-0.8B"
    model_size: str = "0.8B"
    output_dir: str = "jiuzhang-math-0.8b"
    training_method: str = "qlora"
    num_epochs: int = 3
    batch_size: int = 4
    gradient_accumulation: int = 8
    max_seq_length: int = 2048
    curriculum_stages: Dict[int, int] = field(default_factory=lambda: {1: 600, 2: 500, 3: 400, 4: 200})
    eval_steps: int = 100
    save_steps: int = 200
    use_curriculum: bool = True
    use_verifier_reward: bool = True
    fp16: bool = True
    seed: int = 42
    data_path: str = "jiuzhang_curriculum.jsonl"

    def to_dict(self):
        return asdict(self)

    def to_yaml(self) -> str:
        d = asdict(self)
        lines = ["# JiuZhang SmallMathModel Training Configuration", ""]
        for k, v in d.items():
            if isinstance(v, dict):
                lines.append(f"{k}:")
                for kk, vv in v.items():
                    lines.append(f"  {kk}: {vv}")
            else:
                lines.append(f"{k}: {v}")
        return "\n".join(lines)


class SmallMathModelTrainer:
    """Orchestrate training of a small math-specialist model."""

    def __init__(self, config: SmallMathModelConfig):
        self.config = config
        self.pipeline = CurriculumDataPipeline(seed=config.seed)
        self.benchmark = MathBenchmark()

    def generate_training_data(self) -> str:
        if Path(self.config.data_path).exists():
            count = sum(1 for _ in open(self.config.data_path))
            print(f"Training data exists: {self.config.data_path} ({count} samples)")
            return self.config.data_path

        print("Generating curriculum training data ...")
        self.pipeline.generate_all_stages(self.config.curriculum_stages)
        self.pipeline.export_jsonl(self.config.data_path)
        stats = self.pipeline.get_stats()
        print(f"  Total: {stats['total']} samples, SymPy-verified: {stats['verified']}")
        return self.config.data_path

    def evaluate_before_training(self) -> BenchmarkResult:
        return self.benchmark.run(self.config.base_model, "pre-training")

    def build_unsloth_script(self, data_path: str) -> str:
        cfg = self.config
        train_cfg = TRAINING_CONFIGS["qlora"]
        script = f"""#!/usr/bin/env python3
# JiuZhang SmallMathModel — Unsloth QLoRA Training Script
# Auto-generated by jiuzhang.small_math_model

import os
os.environ["WANDB_DISABLED"] = "true"

from unsloth import FastLanguageModel
import torch
from trl import SFTTrainer
from transformers import TrainingArguments
from datasets import load_dataset

# Resolve ModelScope model path
MODEL_NAME = "{cfg.base_model}"
MODEL_PATH = MODEL_NAME
try:
    from modelscope import snapshot_download
    MODEL_PATH = snapshot_download(MODEL_NAME)
    print(f"ModelScope model resolved to: {{MODEL_PATH}}")
except ImportError:
    print("modelscope not installed, falling back to HuggingFace path")
except Exception as e:
    print(f"ModelScope download failed: {{e}}, trying HuggingFace path")

model, tokenizer = FastLanguageModel.from_pretrained(
    model_name=MODEL_PATH,
    max_seq_length={cfg.max_seq_length},
    dtype=None,
    load_in_4bit=True,
)

model = FastLanguageModel.get_peft_model(
    model,
    r={train_cfg['lora_r']},
    lora_alpha={train_cfg['lora_alpha']},
    lora_dropout={train_cfg['lora_dropout']},
    target_modules={train_cfg['target_modules']},
    bias="none",
    use_gradient_checkpointing=True,
    random_state={cfg.seed},
)

dataset = load_dataset("json", data_files="{data_path}", split="train")

def format_chatml(example):
    return {{
        "text": tokenizer.apply_chat_template(example["messages"], tokenize=False)
    }}

dataset = dataset.map(format_chatml)

trainer = SFTTrainer(
    model=model,
    tokenizer=tokenizer,
    train_dataset=dataset,
    args=TrainingArguments(
        per_device_train_batch_size={cfg.batch_size},
        gradient_accumulation_steps={cfg.gradient_accumulation},
        warmup_ratio={train_cfg['warmup_ratio']},
        max_steps=-1,
        num_train_epochs={cfg.num_epochs},
        learning_rate={train_cfg['learning_rate']},
        weight_decay={train_cfg['weight_decay']},
        lr_scheduler_type="{train_cfg['lr_scheduler']}",
        logging_steps=10,
        save_steps={cfg.save_steps},
        output_dir="{cfg.output_dir}",
        seed={cfg.seed},
        bf16=torch.cuda.is_bf16_supported(),
        fp16=not torch.cuda.is_bf16_supported(),
        optim="adamw_8bit",
    ),
)

trainer.train()

model.save_pretrained("{cfg.output_dir}")
tokenizer.save_pretrained("{cfg.output_dir}")
print(f"Model saved to {cfg.output_dir}")

# Export to GGUF
model.save_pretrained_gguf("{cfg.output_dir}", tokenizer)
print(f"GGUF model exported to {cfg.output_dir}")
"""
        path = f"train_unsloth_{cfg.model_size}.py"
        Path(path).write_text(script, encoding="utf-8")
        print(f"Unsloth training script → {path}")
        return path

    def build_hf_script(self, data_path: str) -> str:
        cfg = self.config
        train_cfg = TRAINING_CONFIGS["full"]
        script = f"""#!/usr/bin/env python3
# JiuZhang SmallMathModel — HuggingFace Transformers Full Fine-tuning
# Auto-generated by jiuzhang.small_math_model

import os
os.environ["WANDB_DISABLED"] = "true"

from transformers import (
    AutoModelForCausalLM, AutoTokenizer, Trainer, TrainingArguments, DataCollatorForSeq2Seq
)
from datasets import load_dataset
import torch

model_name = "{cfg.base_model}"
tokenizer = AutoTokenizer.from_pretrained(model_name)
if tokenizer.pad_token is None:
    tokenizer.pad_token = tokenizer.eos_token

model = AutoModelForCausalLM.from_pretrained(
    model_name,
    torch_dtype=torch.bfloat16 if torch.cuda.is_bf16_supported() else torch.float16,
    device_map="auto",
)

dataset = load_dataset("json", data_files="{data_path}", split="train")

def tokenize(example):
    text = tokenizer.apply_chat_template(example["messages"], tokenize=False)
    return tokenizer(text, truncation=True, max_length={cfg.max_seq_length})

tokenized = dataset.map(tokenize, remove_columns=dataset.column_names)

trainer = Trainer(
    model=model,
    args=TrainingArguments(
        output_dir="{cfg.output_dir}",
        per_device_train_batch_size={cfg.batch_size},
        gradient_accumulation_steps={cfg.gradient_accumulation},
        num_train_epochs={cfg.num_epochs},
        learning_rate={train_cfg['learning_rate']},
        weight_decay={train_cfg['weight_decay']},
        warmup_ratio={train_cfg['warmup_ratio']},
        lr_scheduler_type="{train_cfg['lr_scheduler']}",
        logging_steps=10,
        save_steps={cfg.save_steps},
        seed={cfg.seed},
        fp16={cfg.fp16},
        gradient_checkpointing={train_cfg['gradient_checkpointing']},
    ),
    train_dataset=tokenized,
    data_collator=DataCollatorForSeq2Seq(tokenizer=tokenizer, padding=True),
)

trainer.train()
model.save_pretrained("{cfg.output_dir}")
tokenizer.save_pretrained("{cfg.output_dir}")
print(f"Model saved to {cfg.output_dir}")
"""
        path = f"train_hf_{cfg.model_size}.py"
        Path(path).write_text(script, encoding="utf-8")
        print(f"HuggingFace training script → {path}")
        return path

