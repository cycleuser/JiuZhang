def main():
    import argparse
    parser = argparse.ArgumentParser(description="JiuZhang SmallMathModel — Train a math-specialist model")
    sub = parser.add_subparsers(dest="command")

    p_train = sub.add_parser("prepare", help="Prepare training data and scripts")
    p_train.add_argument("--model", default="Qwen/Qwen3.5-0.8B", help="Base model")
    p_train.add_argument("--size", default="0.8B", help="Model size label")
    p_train.add_argument("--method", choices=["qlora", "full", "ollama"], default="qlora")
    p_train.add_argument("--output", default="jiuzhang-math-1.5b")
    p_train.add_argument("--epochs", type=int, default=3)
    p_train.add_argument("--data", default="jiuzhang_curriculum.jsonl")

    p_eval = sub.add_parser("eval", help="Evaluate a trained model")
    p_eval.add_argument("model_path", help="Path to trained model or Ollama model name")
    p_eval.add_argument("--benchmarks", default="gsm8k,algebra,calculus", help="Comma-separated benchmark names")

    p_distill = sub.add_parser("distill", help="Distill from a teacher model")
    p_distill.add_argument("--teacher", default="qwen2.5:7b", help="Teacher model name")
    p_distill.add_argument("--problems", required=True, help="Path to problems JSONL")
    p_distill.add_argument("--output", default="distilled_math.jsonl", help="Output path")

    p_config = sub.add_parser("config", help="Show configuration and report")
    p_config.add_argument("--model", default="Qwen/Qwen3.5-0.8B")
    p_config.add_argument("--size", default="0.8B")

    args = parser.parse_args()

    if not args.command:
        parser.print_help()
        return

    if args.command == "prepare":
        cfg = SmallMathModelConfig(
            base_model=args.model, model_size=args.size,
            training_method=args.method, output_dir=args.output,
            num_epochs=args.epochs, data_path=args.data,
        )
        trainer = SmallMathModelTrainer(cfg)
        data_path = trainer.generate_training_data()
        if args.method == "qlora":
            trainer.build_unsloth_script(data_path)
        elif args.method == "full":
            trainer.build_hf_script(data_path)
        elif args.method == "ollama":
            trainer.build_ollama_modelfile()
        trainer.print_full_report()

    elif args.command == "eval":
        bench = MathBenchmark()
        result = bench.evaluate_local(args.model_path)
        print(f"\nEvaluation results:")
        for k, v in result.scores.items():
            print(f"  {k}: {v:.1%}" if isinstance(v, float) else f"  {k}: {v}")

    elif args.command == "distill":
        cfg = SmallMathModelConfig()
        trainer = SmallMathModelTrainer(cfg)
        trainer.distill_from_teacher(args.teacher, args.problems, args.output)

    elif args.command == "config":
        cfg = SmallMathModelConfig(base_model=args.model, model_size=args.size)
        trainer = SmallMathModelTrainer(cfg)
        trainer.print_full_report()


if __name__ == "__main__":
    main()