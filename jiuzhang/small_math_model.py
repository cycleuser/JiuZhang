"""SmallMathModel — Fine-tuning framework for a small mathematics-specialist model.

Designed for models like Qwen3.5-0.8B, Qwen2.5-1.5B, Phi-3-mini, etc.
Supports three training strategies:
  1. QLoRA via Unsloth (recommended: single GPU, 8-24GB VRAM)
  2. Full fine-tune via HuggingFace Transformers (2+ GPUs)
  3. Ollama custom model via Modelfile (fastest, adapter-level only)

Key features:
  - Curriculum-ordered training data loading
  - SymPy verifier as reward signal (verifier-guided fine-tuning)
  - Automatic evaluation against GSM8K-style benchmark
  - Model distillation: generate teacher outputs from large model, train small model
  - Export to GGUF/Ollama after training
"""

