    def distill_from_teacher(self, teacher_model: str, problems_path: str, output_path: str) -> str:
        """Generate teacher model outputs for distillation.

        Uses the configured LLM client to generate teacher responses,
        which can then be used as training targets for the small model.
        """
        print(f"Generating teacher outputs from {teacher_model} ...")
        problems = []
        with open(problems_path, "r", encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    problems.append(json.loads(line))

        distilled = []
        from jiuzhang.core.multi_provider_api import MultiProviderClient
        from jiuzhang.core.config import Config
        client = MultiProviderClient(Config())

        for i, prob in enumerate(problems):
            prompt = prob.get("input", prob.get("problem", ""))
            try:
                result = client.send_message(
                    [{"role": "user", "content": f"请详细解答以下数学问题，展示完整步骤：\n{prompt}"}],
                    model=teacher_model,
                    max_tokens=2048,
                    temperature=0.1,
                )
                if result.success:
                    distilled.append({
                        "messages": [
                            {"role": "system", "content": "你是数学专家，擅长逐步推理和验证。"},
                            {"role": "user", "content": prompt},
                            {"role": "assistant", "content": result.data},
                        ],
                        "source": f"distilled_from_{teacher_model}",
                        "verified": False,
                    })
            except Exception as e:
                print(f"  Problem {i}: teacher failed — {e}")

            if (i + 1) % 50 == 0:
                print(f"  Processed {i+1}/{len(problems)} problems")

        with open(output_path, "w", encoding="utf-8") as f:
            for entry in distilled:
                f.write(json.dumps(entry, ensure_ascii=False) + "\n")
        print(f"Distilled {len(distilled)} samples → {output_path}")
        return output_path

    def evaluate_model(self, model_path: str) -> BenchmarkResult:
        """Evaluate a trained model against the math benchmark."""
        return self.benchmark.evaluate_local(model_path)

