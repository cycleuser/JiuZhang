#!/usr/bin/env python3
"""JiuZhang End-to-End Math Model Training Pipeline.

Complete workflow:
  1. Merge all training data (curriculum + self-correction + rejection sampling)
  2. Download Qwen3.5-0.8B from ModelScope
  3. Train with QLoRA (low VRAM optimized)
  4. Export to GGUF + Ollama

Usage:
  python train_math_model_end_to_end.py                    # Full pipeline
  python train_math_model_end_to_end.py --step prepare     # Only prepare data
  python train_math_model_end_to_end.py --step download    # Only download model
  python train_math_model_end_to_end.py --step train       # Only train
  python train_math_model_end_to_end.py --step export      # Only export to Ollama
"""

import json
import os
import subprocess
import sys
import time
from pathlib import Path

# Configuration
MODEL_NAME = "Qwen/Qwen3.5-0.8B"
OUTPUT_DIR = "jiuzhang-math-0.8b"
DATA_FILES = [
    "jiuzhang_curriculum.jsonl",
    "jiuzhang_self_correction.jsonl",
    "jiuzhang_rejection_sampling.jsonl",
]
MERGED_DATA = "jiuzhang_merged_training.jsonl"
MAX_SEQ_LENGTH = 1024
LORA_R = 16
LORA_ALPHA = 32
EPOCHS = 3
BATCH_SIZE = 1
GRADIENT_ACCUMULATION = 32
LEARNING_RATE = 2e-4


def step_prepare_data():
    """Merge all training data into a single file."""
    print("=" * 60)
    print("Step 1: Preparing Training Data")
    print("=" * 60)
    
    merged = []
    for f in DATA_FILES:
        if not Path(f).exists():
            print(f"  WARNING: {f} not found, skipping")
            continue
        with open(f) as fh:
            for line in fh:
                line = line.strip()
                if line:
                    try:
                        sample = json.loads(line)
                        # Ensure messages format
                        if "messages" in sample:
                            merged.append(sample)
                    except json.JSONDecodeError:
                        continue
    
    # Shuffle
    import random
    random.seed(42)
    random.shuffle(merged)
    
    # Write merged data
    with open(MERGED_DATA, "w") as fh:
        for sample in merged:
            fh.write(json.dumps(sample, ensure_ascii=False) + "\n")
    
    print(f"  Merged {len(merged)} samples from {len(DATA_FILES)} files")
    print(f"  Output: {MERGED_DATA}")
    print(f"  File size: {Path(MERGED_DATA).stat().st_size / 1024:.1f} KB")
    
    # Statistics
    categories = {}
    for sample in merged:
        cat = sample.get("category", sample.get("stage_name", "unknown"))
        categories[cat] = categories.get(cat, 0) + 1
    
    print("\n  Category distribution:")
    for cat, count in sorted(categories.items(), key=lambda x: -x[1]):
        bar = "#" * (count // 10)
        print(f"    {cat:20s}: {count:5d} {bar}")
    
    return len(merged)


def step_download_model():
    """Download model from ModelScope."""
    print("=" * 60)
    print("Step 2: Downloading Model from ModelScope")
    print("=" * 60)
    print(f"  Model: {MODEL_NAME}")
    
    try:
        from modelscope import snapshot_download
        print("  Downloading... (this may take a while)")
        model_path = snapshot_download(MODEL_NAME)
        print(f"  Model downloaded to: {model_path}")
        return model_path
    except ImportError:
        print("  ERROR: modelscope not installed")
        print("  Install with: pip install modelscope")
        return None
    except Exception as e:
        print(f"  ERROR: Download failed: {e}")
        print("  Trying HuggingFace fallback...")
        try:
            from huggingface_hub import snapshot_download as hf_download
            model_path = hf_download(MODEL_NAME)
            print(f"  Model downloaded from HuggingFace: {model_path}")
            return model_path
        except Exception as e2:
            print(f"  ERROR: HuggingFace also failed: {e2}")
            return None


