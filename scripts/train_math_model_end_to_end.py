def step_export_to_ollama(model_dir=None):
    """Export trained model to Ollama."""
    print("=" * 60)
    print("Step 4: Exporting to Ollama")
    print("=" * 60)
    
    model_dir = model_dir or OUTPUT_DIR
    
    # Check if GGUF exists
    gguf_files = list(Path(model_dir).glob("*.gguf"))
    if not gguf_files:
        print(f"  No GGUF file found in {model_dir}")
        print("  Trying to convert with llama.cpp...")
        print("  (Manual step: convert model to GGUF first)")
        return False
    
    gguf_path = gguf_files[0]
    model_name = "jiuzhang-math-0.8b"
    
    modelfile = 'FROM ' + str(gguf_path) + '''

PARAMETER temperature 0.1
PARAMETER top_p 0.9
PARAMETER num_ctx 4096
PARAMETER presence_penalty 0.2
PARAMETER frequency_penalty 0.2

SYSTEM """You are JiuZhang-Math, a specialized mathematical reasoning model.
You excel at step-by-step proofs, symbolic computation, and problem solving.
Always show your reasoning and verify your answers.
Use both Chinese and English as appropriate."""
'''
    
    modelfile_path = f"Modelfile.{model_name}"
    Path(modelfile_path).write_text(modelfile, encoding="utf-8")
    
    print(f"  Modelfile created: {modelfile_path}")
    print(f"  Run: ollama create {model_name} -f {modelfile_path}")
    
    # Try to create if ollama is available
    try:
        result = subprocess.run(
            ["ollama", "create", model_name, "-f", modelfile_path],
            capture_output=True, text=True, timeout=300
        )
        if result.returncode == 0:
            print(f"  Ollama model created: {model_name}")
            print(f"  Test with: ollama run {model_name} 'Solve: 3x + 7 = 22'")
            return True
        else:
            print(f"  Ollama create failed: {result.stderr}")
            return False
    except FileNotFoundError:
        print("  Ollama not found. Install from https://ollama.ai")
        return False
    except subprocess.TimeoutExpired:
        print("  Ollama create timed out (model may be large)")
        return False


def _detect_device():
    """Detect available hardware."""
    try:
        import torch
        if torch.backends.mps.is_available():
            return "Apple Silicon (MPS)"
        elif torch.cuda.is_available():
            return f"NVIDIA GPU ({torch.cuda.get_device_name(0)})"
    except ImportError:
        pass
    
    import platform
    if platform.system() == "Darwin" and platform.processor() == "arm":
        return "Apple Silicon (no PyTorch)"
    return "CPU"


def main():
    import argparse
    parser = argparse.ArgumentParser(description="JiuZhang End-to-End Math Model Training")
    parser.add_argument("--step", choices=["prepare", "download", "train", "export", "all"],
                       default="all", help="Which step to run")
    parser.add_argument("--model-path", help="Path to downloaded model (skip download)")
    parser.add_argument("--epochs", type=int, default=3, help="Number of epochs")
    parser.add_argument("--lora-r", type=int, default=16, help="LoRA rank")
    parser.add_argument("--output", default="jiuzhang-math-0.8b", help="Output directory")
    args = parser.parse_args()
    
    # Update module-level config
    global EPOCHS, LORA_R, OUTPUT_DIR
    EPOCHS = args.epochs
    LORA_R = args.lora_r
    OUTPUT_DIR = args.output
    
    print("JiuZhang Math Model Training Pipeline")
    print("Device: " + _detect_device())
    print()
    
    model_path = args.model_path
    
    if args.step in ("prepare", "all"):
        num_samples = step_prepare_data()
        if num_samples == 0:
            print("ERROR: No training data found!")
            sys.exit(1)
    
    if args.step in ("download", "all"):
        if not model_path:
            model_path = step_download_model()
            if not model_path:
                print("ERROR: Model download failed!")
                sys.exit(1)
    
    if args.step in ("train", "all"):
        script_path = step_generate_training_script(model_path)
        print("\nTo start training, run:")
        print("  python " + script_path)
        print("\nTraining will take approximately %d hours on Apple Silicon." % (EPOCHS * 2))
        print("You can monitor progress in the output logs.")
    
    if args.step in ("export", "all"):
        step_export_to_ollama()


if __name__ == "__main__":
    main()
